import { apiFor, closeBrowser, STORE, STORE2, log } from './lib-wh.mjs'
const a = await apiFor('admin')
const me = await a.get('maison_pos.api.shipping.me')
log('main_warehouse', me.main_warehouse, 'wh boutique', me.warehouse_boutique, 'provider', me.provider, 'tz', me.time_zone)
log('stores', JSON.stringify(me.stores).slice(0,600))
const b = await a.list('Maison Boutique', {}, ['name','boutique_name','warehouse','transit_warehouse','damaged_warehouse','company','is_warehouse','enabled'], 50)
log('boutiques:'); for (const x of b) log(' ', JSON.stringify(x))
const settings = await a.doc('Maison POS Settings','Maison POS Settings').catch(e=>({err:String(e).slice(0,200)}))
const keys = Object.keys(settings||{}).filter(k=>/wall|print|low_stock|shipping|ship_from|digest|reorder/.test(k))
log('settings:', JSON.stringify(Object.fromEntries(keys.map(k=>[k,settings[k]]))))
log('--- open alerts by boutique')
const al = await a.get('maison_pos.api.inventory.alerts', { status: 'all', limit: 500 })
log('alerts total', al.alerts.length, 'counts', JSON.stringify(al.counts))
log('--- open shipments')
const sh = await a.get('maison_pos.api.shipping.shipments', { status: 'all', limit: 500 })
log('shipments', sh.count, JSON.stringify(sh.shipments.map(s=>[s.name,s.boutique,s.status])).slice(0,1500))
const rq = await a.get('maison_pos.api.shipping.requests_list', { status: 'all', limit: 500 })
log('requests', rq.count, JSON.stringify(rq.requests.map(s=>[s.name,s.boutique,s.status])).slice(0,1500))
const dq = await a.get('maison_pos.api.shipping.discrepancies', { status: 'all', limit: 200 })
log('discrepancies', dq.count, JSON.stringify(dq.discrepancies.map(s=>[s.name,s.boutique,s.type,s.status])).slice(0,800))
log('--- workflow?')
log(JSON.stringify(await a.list('Workflow', {document_type:'Maison Replenishment Request'}, ['name','is_active'])))
log('--- scheduler jobs')
log(JSON.stringify(await a.list('Scheduled Job Type', {method:['like','%maison_pos%']}, ['name','method','frequency','stopped'], 50)))
await a.dispose(); await closeBrowser()
